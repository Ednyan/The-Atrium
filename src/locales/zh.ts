// Simplified Chinese (zh-Hans), offered under the bare `zh` tag.
//
// Register is the ordinary one for software in Chinese: concise, imperative,
// and with the second person usually dropped rather than argued over -- 你 is
// too familiar for some readers and 您 too deferential for a creative tool, so
// most lines simply do not need a pronoun at all. Where one is unavoidable,
// 你 is used, matching the tone the English keeps.
//
// Full-width punctuation throughout (，。？：「」（）), because half-width marks
// beside Han characters read as broken spacing rather than as style. Latin
// words and numbers keep a thin gap from the Han text around them by the
// browser's own rules; no manual spaces are inserted.
//
// Kept untranslated, per the glossary in README.md: The Digital Atrium,
// Atrium and Trace/trace. Chinese does have 中庭 for the architectural
// feature, and it was tempting -- but here the word is the product's own
// vocabulary rather than a description of a room, and a reader who meets
// "Atrium" in the interface will meet it again in the URL, the desktop app's
// title bar and every screenshot. Third-party names (Pinterest, Google,
// Stripe) stay in Latin script for the same reason.
//
// Untranslated keys fall back to English, so this file grows a surface at a
// time without ever leaving the app broken.

