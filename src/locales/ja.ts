// Japanese.
//
// Register is ですます throughout for anything that speaks to the reader --
// hints, errors, explanations -- while buttons and labels take the noun form
// (体言止め) that Japanese interfaces use: 保存, 閉じる, 変更を保存. Mixing the
// two is not an inconsistency here; it is the convention.
//
// Full-width punctuation （。、「」） and full-width parentheses around Japanese
// text, half-width around Latin. Numbers keep their counters -- 3 つ, 10 件,
// {count} 人 -- since a bare number reads as unfinished in Japanese.
//
// Kept untranslated, per the glossary in README.md: The Digital Atrium,
// Atrium and Trace/trace. Both would transliterate comfortably into katakana
// (アトリウム, トレース) and アトリウム is even a normal Japanese word for the
// architectural feature -- but they are the product's own vocabulary, met
// again in the URL, the title bar and every screenshot, so they stay in Latin
// script as they do in the other catalogues. Third-party names likewise.
//
// Untranslated keys fall back to English, so this file grows a surface at a
// time without ever leaving the app broken.

