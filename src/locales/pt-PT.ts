// file. European avoids the gerund in favour of “a + infinitive” — “a
// carregar” rather than “carregando” — and puts the definite article before
// a possessive — “o seu email”, “a sua conta” — where Brazilian drops it.
// Both are the single most reliable tell between the two dialects to a
// native reader, so they are applied consistently rather than left as the
// Brazilian construction with different words in it.
//
