// Korean.
//
// Buttons and labels take the noun form Korean interfaces use -- 저장, 취소,
// 닫기 -- while anything that speaks to the reader is in 해요체: warm rather
// than the stiffer 합니다체, which matches the quiet register the English
// keeps. Errors stay in the same voice; a message that switches to formal
// address only when something goes wrong reads as a different app scolding
// you.
//
// Particles are the one thing that cannot be left to chance. 을/를, 이/가 and
// 은/는 each pick their form from whether the preceding syllable ends in a
// consonant, which is unknowable when the preceding syllable is {name} or
// {count}. Where a placeholder is followed by a particle, the honorific 님 is
// placed between them -- it always ends in ㅁ, so the particle that follows is
// always the consonant form. Counts take a counter (개, 명, 건) for the same
// reason a bare number reads as unfinished.
//
// Kept untranslated, per the glossary in README.md: The Digital Atrium,
// Atrium and Trace/trace, along with third-party names. Korean would take
// 아트리움 and 트레이스 comfortably, but they are the product's own
// vocabulary, met again in the URL and the title bar.
//
// Untranslated keys fall back to English, so this file grows a surface at a
// time without ever leaving the app broken.

